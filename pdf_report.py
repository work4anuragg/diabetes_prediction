"""Generate a styled PDF report for a single prediction."""
from datetime import datetime
from io import BytesIO

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import (Paragraph, SimpleDocTemplate, Spacer, Table,
                                TableStyle)


def build_pdf(user: dict, inputs: dict, prediction: int, risk: float,
              model_name: str, accuracy: float) -> bytes:
    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4,
                            leftMargin=2*cm, rightMargin=2*cm,
                            topMargin=2*cm, bottomMargin=2*cm)
    styles = getSampleStyleSheet()
    title = ParagraphStyle("title", parent=styles["Title"],
                           textColor=colors.HexColor("#0d47a1"), fontSize=22)
    h2 = ParagraphStyle("h2", parent=styles["Heading2"],
                        textColor=colors.HexColor("#0d47a1"))
    body = styles["BodyText"]

    story = []
    story.append(Paragraph("AI Diabetes Risk Assessment Report", title))
    story.append(Spacer(1, 0.3*cm))
    story.append(Paragraph(
        f"Generated on {datetime.now().strftime('%d %B %Y, %H:%M')}", body))
    story.append(Spacer(1, 0.6*cm))

    story.append(Paragraph("Patient Information", h2))
    pt = Table([
        ["Name", user.get("full_name") or user["username"]],
        ["Username", user["username"]],
        ["Email", user.get("email") or "—"],
    ], colWidths=[5*cm, 10*cm])
    pt.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#e3f2fd")),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.grey),
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(pt)
    story.append(Spacer(1, 0.5*cm))

    story.append(Paragraph("Clinical Inputs", h2))
    rows = [["Parameter", "Value"]]
    for k, v in inputs.items():
        rows.append([k, f"{v}"])
    t = Table(rows, colWidths=[8*cm, 7*cm])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0d47a1")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.grey),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1),
         [colors.white, colors.HexColor("#f5faff")]),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    story.append(t)
    story.append(Spacer(1, 0.6*cm))

    story.append(Paragraph("Prediction Result", h2))
    verdict = "DIABETIC (positive)" if prediction == 1 else "NON-DIABETIC (negative)"
    band = "Low" if risk < 30 else ("Moderate" if risk < 60 else "High")
    color = colors.HexColor("#c62828" if prediction == 1 else "#2e7d32")
    rt = Table([
        ["Verdict", verdict],
        ["Risk Probability", f"{risk:.2f}%"],
        ["Risk Band", band],
        ["Model Used", model_name],
        ["Model Accuracy (test set)", f"{accuracy*100:.2f}%"],
    ], colWidths=[6*cm, 9*cm])
    rt.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#e3f2fd")),
        ("TEXTCOLOR", (1, 0), (1, 0), color),
        ("FONTNAME", (1, 0), (1, 0), "Helvetica-Bold"),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.grey),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(rt)
    story.append(Spacer(1, 0.7*cm))

    story.append(Paragraph("Disclaimer", h2))
    story.append(Paragraph(
        "This report is generated by a machine-learning model trained on the "
        "Pima Indians Diabetes Database for academic and research purposes. "
        "It is <b>not</b> a clinical diagnosis. Please consult a qualified "
        "physician for medical advice.", body))

    doc.build(story)
    return buf.getvalue()
